-- #176: a stored icon is the Lucide name of a catalogue icon (packages/types/src/icons.ts),
-- and a new row defaults to one. The legacy picker stored Heroicons names (`heroicon-o-truck`,
-- in its o/s/m/c variants); each with a close catalogue icon is rewritten to it here, in the
-- three tables that hold one. The rest are interface glyphs (arrows, chevrons, text marks) no
-- record would mean: they stay as they were, draw a fallback, are named by the import's verify
-- step, and the form asks for an icon when the record is next saved. The import replays this
-- migration over every snapshot it loads, so a re-import lands Lucide names too.

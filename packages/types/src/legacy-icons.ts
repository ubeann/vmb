const HEROICON = /^heroicon-[a-z]-(.+)$/;

/**
 * A stored icon as migration `0032` would leave it: a Heroicons name with a
 * counterpart becomes that catalogue icon, and anything else is returned
 * unchanged for the verifier's `icon-name` warning to name.
 */
export function lucideForLegacyIcon(name: string): string {
  const heroicon = HEROICON.exec(name)?.[1];
  return heroicon !== undefined && Object.hasOwn(HEROICON_LUCIDE, heroicon)
    ? (HEROICON_LUCIDE[heroicon] as IconName)
    : name;
}
